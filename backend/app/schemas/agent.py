"""Published contracts for the external agent gateway (/api/agent/v1).

These Pydantic models are the single source for:
  - FastAPI request validation and the OpenAPI document (/openapi.json)
  - JSON Schema artifacts in /schemas (generated by `python -m scripts.export_schemas`)
"""
from __future__ import annotations

from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field

from app.schemas import ProcurementCreate, ProcurementIntent

SCHEMA_VERSION = "aimo-protocol/procurement-decision@1"


class AgentProcureRequest(ProcurementCreate):
    """Procurement request submitted by an external purchasing agent."""

    model_config = ConfigDict(json_schema_extra={"examples": [{
        "text": "I need 1,000 litres of lactose-free milk by Monday. Prioritise price.",
        "confirm_assumptions": False,
    }]})


class ErrorResponse(BaseModel):
    error: str = Field(description="Human-readable message (never contains secrets or stack traces)")
    code: str = Field(description="Stable machine-readable error code, e.g. NOT_FOUND, FORBIDDEN, RATE_LIMITED")
    correlation_id: str | None = Field(default=None, description="Echo of X-Correlation-ID for support and audit lookup")
    details: list[dict[str, Any]] | None = None


class PolicyRef(BaseModel):
    id: str | None
    name: str | None
    version: int | None


class AgentRef(BaseModel):
    id: str | None
    acting_for: str | None = None


class DecisionReason(BaseModel):
    code: str
    outcome: Literal["ALLOWED", "REQUIRES_APPROVAL", "BLOCKED"]
    message: str


class HumanApproval(BaseModel):
    required: bool
    approval_id: str | None = None
    status: str | None = None
    decided_by: str | None = None
    decided_at: str | None = None
    reason: str | None = None


class SelectedProduct(BaseModel):
    model_config = ConfigDict(extra="allow")
    product_id: str
    name: str | None = None
    quantity: float | None = None
    sales_unit: str | None = None
    unit_price_excl_tax: float | None = None
    total_excl_tax: float | None = None
    total_incl_tax: float | None = None
    currency: str | None = None
    price_status: Literal["VERIFIED", "UNVERIFIED", "UNAVAILABLE", "API_ERROR", "TIMEOUT"] | None = None
    availability_status: Literal["AVAILABLE", "AVAILABLE_QTY_UNCONFIRMED", "PARTIAL", "LATE", "UNAVAILABLE", "UNKNOWN",
                                 "API_ERROR", "TIMEOUT"] | None = None
    source: str | None = None
    substitute_for: str | None = None


class Evidence(BaseModel):
    model_config = ConfigDict(extra="allow")
    id: str
    claim: str
    value: Any = None
    state: Literal["VERIFIED", "UNKNOWN", "ERROR"]
    source: str | None = None
    product_id: str | None = None
    timestamp: str | None = None
    detail: str | None = None


class Proposal(BaseModel):
    id: str
    status: Literal["PROPOSAL_READY_NOT_SUBMITTED"]
    submitted_to_supplier: Literal[False]
    total_excl_tax: float | None = None
    currency: str | None = None


class LifecycleStage(BaseModel):
    stage: Literal["RECOMMENDATION", "POLICY_DECISION", "HUMAN_APPROVAL", "PROCUREMENT_PROPOSAL", "SUPPLIER_ORDER"]
    state: str
    detail: str


class ProcurementDecisionV1(BaseModel):
    """Machine-readable outcome of a procurement request. No supplier order is ever placed."""

    model_config = ConfigDict(extra="allow")
    schema_: Literal["aimo-protocol/procurement-decision@1"] = Field(alias="schema")
    request_id: str
    decision_id: str | None
    created_at: str | None
    channel: Literal["WORKSPACE", "AGENT_API"]
    organization_id: str | None = None
    correlation_id: str | None = None
    agent: AgentRef
    policy: PolicyRef
    request_text: str = Field(description="Original natural-language request, preserved verbatim")
    overrides: dict[str, Any] = Field(default_factory=dict, description="Structured overrides supplied by the caller")
    parser: str
    intent: ProcurementIntent | dict[str, Any]
    status: str
    decision: Literal["ALLOWED", "REQUIRES_APPROVAL", "BLOCKED"] | None
    reasons: list[DecisionReason]
    human_approval: HumanApproval
    selected: SelectedProduct | None
    evidence_refs: list[str]
    evidence: list[Evidence]
    proposal: Proposal | None
    lifecycle: list[LifecycleStage]
    pipeline: list[dict[str, Any]] = Field(default_factory=list, description="Backend-confirmed pipeline stages")
    recommendations: list[dict[str, Any]]
    excluded: list[dict[str, Any]]
    comparison: dict[str, Any] | None = None
    ranking_explanation: dict[str, Any] | None = None
    summary: dict[str, Any]
    supplier_order_placed: Literal[False]
    disclaimer: str


class AgentIdentity(BaseModel):
    agent_id: str
    name: str
    organization_id: str | None
    scopes: list[str]
    key_id: str | None
    rate_limit_per_minute: int


SCHEMAS: dict[str, type[BaseModel]] = {
    "agent-procure-request.v1": AgentProcureRequest,
    "procurement-decision.v1": ProcurementDecisionV1,
    "error.v1": ErrorResponse,
    "agent-identity.v1": AgentIdentity,
}


def json_schema(name: str) -> dict:
    model = SCHEMAS[name]
    schema = model.model_json_schema(by_alias=True)
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    schema["$id"] = f"https://aimo-protocol.local/schemas/{name}.json"
    return schema
